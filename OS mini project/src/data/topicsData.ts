export function getAllLessons() {
  return TOPIC_CATEGORIES.flatMap(cat => cat.lessons);
}

export function findLessonByPath(path: string) {
  const clean = path.split('?')[0];
  return getAllLessons().find(l => l.path.split('?')[0] === clean);
}
